func writeSources(path string, devs []*device) error {
	var b strings.Builder
	b.WriteString(sourcesHeader)
	for _, d := range devs {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", d.Name, d.Family, d.Arch, d.Core, d.Source)
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
