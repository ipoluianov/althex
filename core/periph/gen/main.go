// Command gen builds the compact peripheral-register database embedded by
// package periph from CMSIS-SVD and Microchip ATDF files.
//
//	go run ./core/periph/gen -out core/periph/data [-cache DIR] [-only SUBSTR]
//
// Source files are downloaded once into the cache directory (outside the
// repository) and are parsed as data only, with size limits.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"
)

func main() {
	out := flag.String("out", "core/periph/data", "output directory")
	cacheDef := filepath.Join(os.TempDir(), "althex-periph-src")
	if d, err := os.UserCacheDir(); err == nil {
		cacheDef = filepath.Join(d, "althex-periph-src")
	}
	cache := flag.String("cache", cacheDef, "download cache directory (outside the repository)")
	only := flag.String("only", "", "build only devices whose name contains this substring (debugging)")
	flag.Parse()

	var sel []spec
	for _, s := range specs {
		if *only == "" || strings.Contains(strings.ToLower(s.dev.Name), strings.ToLower(*only)) {
			sel = append(sel, s)
		}
	}
	// download in parallel
	type res struct {
		data []byte
		err  error
	}
	results := make([]res, len(sel))
	var wg sync.WaitGroup
	sem := make(chan struct{}, 6)
	var mu sync.Mutex // serialises downloads of the same archive
	archives := map[string]*sync.Mutex{}
	for i := range sel {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			u, _, _ := strings.Cut(sel[i].src, "#")
			mu.Lock()
			m := archives[u]
			if m == nil {
				m = &sync.Mutex{}
				archives[u] = m
			}
			mu.Unlock()
			m.Lock()
			data, err := fetchSource(*cache, sel[i].src)
			m.Unlock()
			results[i] = res{data, err}
		}(i)
	}
	wg.Wait()

	var devs []*device
	failed := 0
	notices := map[string][]string{} // licence text -> devices
	for i, s := range sel {
		if results[i].err != nil {
			fmt.Fprintf(os.Stderr, "SKIP %s: %v\n", s.dev.Name, results[i].err)
			failed++
			continue
		}
		if s.kind != "atdf" {
			if t := notice(results[i].data); t != "" {
				notices[t] = append(notices[t], s.dev.Name)
			}
		}
		d := s.dev // copy of the hand-written fields
		d.Memory = append([]region(nil), s.dev.Memory...)
		d.Source = s.src
		var err error
		if s.kind == "atdf" {
			err = parseATDF(results[i].data, &d)
		} else {
			err = parseSVD(results[i].data, &d)
		}
		if err != nil {
			fmt.Fprintf(os.Stderr, "SKIP %s: %v\n", s.dev.Name, err)
			failed++
			continue
		}
		d.Parts = expandParts(d.Patterns, s.partsDef)
		sortRegions(d.Memory)
		nregs := 0
		for _, p := range d.Periphs {
			for _, r := range p.Layout.Regs {
				nregs += max(r.Dim, 1)
			}
		}
		fmt.Fprintf(os.Stderr, "%-24s %-8s %-22s periph=%-4d regs=%-6d irq=%d\n", d.Name, d.Arch, d.Core, len(d.Periphs), nregs, len(d.Interrupts))
		devs = append(devs, &d)
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	size, err := writeDB(*out, devs)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if *only == "" {
		if err := writeSources(filepath.Join(*out, "SOURCES.md"), devs); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := writeNotices(filepath.Join(*out, "NOTICES.txt"), notices); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	fmt.Fprintf(os.Stderr, "%d devices (%d skipped), database size %d bytes (%.2f MB)\n", len(devs), failed, size, float64(size)/(1<<20))
	if failed > 0 {
		os.Exit(2)
	}
}

